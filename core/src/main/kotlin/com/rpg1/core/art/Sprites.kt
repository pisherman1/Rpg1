        'h' to 0xFF6B3D22.toInt(), // hair
        'y' to 0xFFF2C641.toInt(), // gold
        'g' to 0xFFA8AEB8.toInt(), // steel
        'G' to 0xFF5A606A.toInt(),
        'b' to 0xFF3A6AD8.toInt(),
