    )
}

class Sprite(val name: String, val rows: List<String>) {
    val width get() = rows.first().length
    val height get() = rows.size

    /** ARGB pixels, row-major; transparent pixels are 0. */
    fun pixels(overrides: Map<Char, Int> = emptyMap()): IntArray = IntArray(width * height) { i ->
        val c = rows[i / width][i % width]
        if (c == '.') 0 else overrides[c] ?: Palette.colors[c] ?: error("Unknown palette key '$c' in $name")
    }
}

