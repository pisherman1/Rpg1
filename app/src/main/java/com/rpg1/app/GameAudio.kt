package com.rpg1.app

import android.content.Context
import android.content.SharedPreferences
import android.media.AudioAttributes
import android.media.MediaPlayer
import android.media.SoundPool
import android.os.Handler
import android.os.Looper
import android.util.Log
import com.rpg1.audio.Dsp
import com.rpg1.audio.Music
import com.rpg1.audio.Sfx
import com.rpg1.audio.Synth
import com.rpg1.core.audio.SoundId
import com.rpg1.core.audio.TrackId
import java.io.File
import java.util.EnumMap
import java.util.concurrent.ConcurrentHashMap
import kotlin.concurrent.thread
import kotlin.random.Random

/**
 * Plays the synthesised sound effects (SoundPool) and music (MediaPlayer with crossfades).
 * All audio is generated by the audio module on first launch and cached as WAV files.
 */
object GameAudio {
    /** Bump when the synth or compositions change so the cache is regenerated. */
    private const val CACHE_VERSION = 1
    private const val MUSIC_VOLUME = 0.55f
    private const val FADE_MS = 700L

    private lateinit var prefs: SharedPreferences
    private lateinit var dir: File
    private val main = Handler(Looper.getMainLooper())

    private var pool: SoundPool? = null
    private val samples = EnumMap<SoundId, Int>(SoundId::class.java)
    private val loaded = ConcurrentHashMap.newKeySet<Int>()
    private val lastPlayed = EnumMap<SoundId, Long>(SoundId::class.java)

    @Volatile private var musicReady = false
    private var player: MediaPlayer? = null
    private var playing: TrackId? = null
    private var wanted: TrackId? = null
    private var paused = false

    var musicOn: Boolean
        get() = prefs.getBoolean("music", true)
        set(v) {
            prefs.edit().putBoolean("music", v).apply()
            applyMusic()
        }

    var soundOn: Boolean
        get() = prefs.getBoolean("sound", true)
        set(v) = prefs.edit().putBoolean("sound", v).apply()

    fun init(context: Context) {
        if (::prefs.isInitialized) return
        prefs = context.getSharedPreferences("audio", Context.MODE_PRIVATE)
        dir = File(context.cacheDir, "audio-v$CACHE_VERSION")
        thread(name = "audio-render", isDaemon = true) {
            try {
                dir.mkdirs()
                dir.parentFile?.listFiles { f -> f.name.startsWith("audio-v") && f != dir }?.forEach { it.deleteRecursively() }
                val sp = SoundPool.Builder()
                    .setMaxStreams(10)
                    .setAudioAttributes(AudioAttributes.Builder()
                        .setUsage(AudioAttributes.USAGE_GAME)
                        .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                        .build())
                    .build()
                sp.setOnLoadCompleteListener { _, sample, status -> if (status == 0) loaded += sample }
                for (id in SoundId.entries) {
                    val f = cached("sfx_${id.name.lowercase()}.wav") { Sfx.render(id) }
                    samples[id] = sp.load(f.path, 1)
                }
                pool = sp
                // Music renders after the effects so sounds work right away.
                for (t in TrackId.entries) cached("music_${t.name.lowercase()}.wav") { Music.render(t) }
                musicReady = true
                main.post { applyMusic() }
            } catch (t: Throwable) {
                Log.e("DungeonDelver", "Audio setup failed", t)
            }
        }
    }

    private fun cached(name: String, render: () -> ShortArray): File {
        val f = File(dir, name)
        if (f.length() > 44) return f
        val tmp = File(dir, "$name.tmp")
        tmp.writeBytes(Dsp.wav(render(), Synth.RATE))
        tmp.renameTo(f)
        return f
    }

    // --- Effects ---------------------------------------------------------------

    fun play(id: SoundId) {
        if (!::prefs.isInitialized || !soundOn || paused) return
        val sp = pool ?: return
        val sample = samples[id] ?: return
        if (sample !in loaded) return
        val now = android.os.SystemClock.uptimeMillis()
        val gap = if (id == SoundId.STEP) 190L else 40L
        if (now - (lastPlayed[id] ?: 0L) < gap) return
        lastPlayed[id] = now
        val volume = when (id) {
            SoundId.STEP -> 0.35f
            SoundId.CLICK -> 0.5f
            else -> 0.9f
        }
        // A little pitch variety keeps repeated sounds from feeling mechanical.
        val varied = id in setOf(SoundId.STEP, SoundId.HIT, SoundId.MISS, SoundId.BOW, SoundId.COIN, SoundId.MONSTER_DIE)
        val rate = if (varied) 0.92f + Random.nextFloat() * 0.16f else 1f
        sp.play(sample, volume, volume, 1, 0, rate)
    }

    // --- Music -----------------------------------------------------------------

    /** Requests a track (or silence); switching crossfades. Call from the main thread. */
    fun setMusic(track: TrackId?) {
        if (track == wanted) return
        wanted = track
        applyMusic()
    }

    private fun applyMusic() {
        if (!::prefs.isInitialized || !musicReady) return
        val target = if (musicOn && !paused) wanted else null
        if (target == playing && (target == null || player != null)) return
        player?.let { fadeOut(it) }
        player = null
        playing = target
        if (target == null) return
        try {
            val mp = MediaPlayer()
            mp.setAudioAttributes(AudioAttributes.Builder()
                .setUsage(AudioAttributes.USAGE_GAME)
                .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
                .build())
            mp.setDataSource(File(dir, "music_${target.name.lowercase()}.wav").path)
            mp.isLooping = target.loop
            mp.prepare()
            mp.setVolume(0f, 0f)
            mp.start()
            player = mp
            fade(mp, 0f, MUSIC_VOLUME) {}
        } catch (t: Throwable) {
            Log.e("DungeonDelver", "Couldn't play $target", t)
        }
    }

    private fun fadeOut(mp: MediaPlayer) = fade(mp, MUSIC_VOLUME, 0f) {
        try {
            mp.stop()
        } catch (_: IllegalStateException) {
        }
        mp.release()
    }

    private fun fade(mp: MediaPlayer, from: Float, to: Float, done: () -> Unit) {
        val steps = 14
        for (i in 1..steps) {
            main.postDelayed({
                try {
                    val v = from + (to - from) * i / steps
                    mp.setVolume(v, v)
                } catch (_: IllegalStateException) {
                }
                if (i == steps) done()
            }, FADE_MS * i / steps)
        }
    }

    fun pause() {
        if (!::prefs.isInitialized) return
        paused = true
        pool?.autoPause()
        player?.let { if (it.isPlaying) it.pause() }
    }

    fun resume() {
        if (!::prefs.isInitialized) return
        paused = false
        pool?.autoResume()
        val mp = player
        if (mp != null && playing != null && musicOn) mp.start() else applyMusic()
    }
}
